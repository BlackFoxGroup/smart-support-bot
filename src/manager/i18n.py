def t(lang: str, key: str) -> str:
    row = T.get(key) or {}
    code = lang if lang in LANGS else "en"
    return row.get(code) or row.get("en") or key


def lang_file(data_dir) -> "Path":
    from pathlib import Path

    p = Path(data_dir) / "live_catalog" / "manager_lang.txt"
    p.parent.mkdir(parents=True, exist_ok=True)
    return p


def save_lang(data_dir, lang: str) -> None:
    if lang not in LANGS:
        lang = "en"
    lang_file(data_dir).write_text(lang, encoding="utf-8")


def load_saved_lang(data_dir) -> str:
    path = lang_file(data_dir)
    if not path.is_file():
        return ""
    val = path.read_text(encoding="utf-8").strip()
    return val if val in LANGS else ""
